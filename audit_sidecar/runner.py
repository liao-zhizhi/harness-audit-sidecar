"""Witness collection: run a real command and look at what actually happened.

This module is the eyes and ears of the sidecar. The verdict engine can
only be as honest as the evidence handed to it, so two things matter here:

1. **The exit status must be the command's, not the pipeline's tail.**
   Bash reports the status of the last stage by default, so ``false | cat``
   exits 0 and an agent that pipes its work through a filter can hide a
   failure without lying. ``set -o pipefail`` fixes that; ``PIPESTATUS`` is
   recorded as well, so the report can name the stage that failed.

2. **The witness must be read at the intent's coordinate, not the action's.**
   If a command runs in the wrong directory and the audit then looks for
   the result in that same wrong directory, it will find it, and report a
   confident PASS for work that never reached its target. ``witness_root``
   exists to pin the observation point independently of ``cwd``.

Because of (2) the effect is only ever ``True``/``False`` when the caller
supplied ``expected_file``. With no witness there is nothing to observe,
and the engine is handed ``None`` so that the outcome is ``INVALID`` rather
than a manufactured PASS.
"""

from __future__ import annotations

import logging
import os
import shlex
import subprocess
import tempfile
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Dict, List, Optional, Sequence, Tuple

from .git_witness import GitWitness, GitWitnessError
from .immune_state import TIER_ADAPTIVE, TIER_INNATE
from .verdict import Verdict, VerdictEngine

__all__ = [
    "ExecutionResult",
    "ParentPrecheck",
    "SafeRunner",
    "DEFAULT_TIMEOUT",
    "WITNESS_SCOPE_FULL",
    "WITNESS_SCOPE_STAT",
]
_LOG = logging.getLogger(__name__)

#: Full witness: git change set plus a content read of the artefact.
WITNESS_SCOPE_FULL = "full"
#: Innate witness: existence and mtime of the claimed paths, nothing else.
WITNESS_SCOPE_STAT = "stat"

_SCOPES = (WITNESS_SCOPE_FULL, WITNESS_SCOPE_STAT)

DEFAULT_TIMEOUT = 30.0

# The wrapper is written to a temporary file and executed by bash. Running
# the user command through a script (rather than ``bash -c``) is what makes
# it possible to read PIPESTATUS *after* the command without interfering
# with the command's own stdout or stderr.
_WRAPPER_TEMPLATE = """#!/bin/bash
# Generated by audit_sidecar.runner.
# pipefail: a pipeline fails if any stage fails, not just the last one.
set -o pipefail
{command}
# Read PIPESTATUS before any other command runs, otherwise the array is
# overwritten by the very next simple command (including an assignment).
_audit_pipestatus=("${{PIPESTATUS[@]}}")
printf '%s\\n' "${{_audit_pipestatus[*]}}" > {status_file}
# pipefail semantics: the pipeline status is the rightmost non-zero stage.
_audit_status=${{_audit_pipestatus[-1]}}
for _audit_stage_status in "${{_audit_pipestatus[@]}}"; do
    if [ "$_audit_stage_status" -ne 0 ]; then
        _audit_status=$_audit_stage_status
    fi
done
# Exit with the command's status, not with printf's.
exit "$_audit_status"
"""


@dataclass(frozen=True)
class ParentPrecheck:
    """One declared path whose parent directory was missing before execute.

    Informational only. Presence never changes the lattice verdict; the
    command still runs and the post-effect witness still judges.
    """

    path: str
    missing_dir: str
    timestamp: str


@dataclass(frozen=True)
class ExecutionResult:
    """One audited command execution.

    ``intent`` is the human description of what the command was supposed to
    achieve. The machine-comparable form of the intent is always the boolean
    ``True`` ("the intended effect is present"), because the engine compares
    a witnessed world-state to an intended world-state.

    ``effect_observed`` is ``None`` when no witness was requested. That is a
    deliberate third value, not an error: "we did not look" is different from
    "we looked and found nothing".
    """

    intent: str
    effect_observed: Optional[bool]
    check_observed: bool
    verdict: Verdict
    command: str = ""
    cwd: str = ""
    exit_code: Optional[int] = None
    pipe_status: Tuple[int, ...] = ()
    witness_path: Optional[str] = None
    reason: str = ""
    stdout: str = ""
    stderr: str = ""
    error: Optional[str] = None
    # "exit-status" when the claim came from the command, "protocol" when it
    # came from a tool layer that reported to the agent.
    check_source: str = "exit-status"
    # Git witness fields, empty unless expected_files_modified was supplied.
    git_repo: Optional[str] = None
    changed_files: Tuple[str, ...] = ()
    missing_expected: Tuple[str, ...] = ()
    unexpected_changes: Tuple[str, ...] = ()
    # Judgment-base provenance, empty unless a rule engine judged this call.
    # ``rule_id`` names the rule that decided the verdict, so a trace can be
    # read without the policy that produced it to hand.
    rule_id: Optional[str] = None
    rules_matched: Tuple[str, ...] = ()
    rules_violated: Tuple[str, ...] = ()
    # Which witness class was actually collected. Recorded rather than inferred
    # from the verdict, because a PASS on a cheap witness and a PASS on the
    # full change set are different claims about the world and a reader of the
    # trace has to be able to tell them apart.
    witness_scope: str = WITNESS_SCOPE_FULL
    # Modification time of the primary witnessed path, in seconds since the
    # epoch. Set only by the innate tier, where mtime *is* the evidence.
    witness_mtime: Optional[float] = None
    # Assertions the caller supplied that the collected witness could not
    # evaluate. Empty in the normal case. A non-empty tuple means the verdict
    # is about *less* than the caller asked for, and the trace says so instead
    # of letting a weaker claim read as a full one.
    dropped_assertions: Tuple[str, ...] = ()
    # Parent-directory existence, checked before the command. Empty when
    # every declared path had a directory to land in. Does not affect verdict.
    prechecks: Tuple[ParentPrecheck, ...] = ()

    @property
    def ok(self) -> bool:
        """True only for a PASS. Anything else is not a green light."""
        return self.verdict is Verdict.PASS

    @property
    def tier(self) -> str:
        """The defence tier this record came from, derived from what ran.

        Derived, not stored: a tier that could disagree with the witness it
        labels would be a label about a label.
        """
        if self.witness_scope == WITNESS_SCOPE_STAT:
            return TIER_INNATE
        return TIER_ADAPTIVE


def _read_text(path: str) -> str:
    with open(path, "rb") as handle:
        return handle.read().decode("utf-8", errors="replace")


class SafeRunner:
    """Execute shell commands and judge them against independently read state."""

    def __init__(
        self,
        engine: Optional[VerdictEngine] = None,
        bash: str = "/bin/bash",
        timeout: float = DEFAULT_TIMEOUT,
    ) -> None:
        if not os.path.isfile(bash):
            raise FileNotFoundError("bash interpreter not found: {}".format(bash))
        if timeout <= 0:
            raise ValueError("timeout must be positive, got {}".format(timeout))
        self._engine = engine if engine is not None else VerdictEngine()
        self._bash = bash
        self._timeout = float(timeout)

    def with_engine(self, engine) -> "SafeRunner":
        """Return an equivalent runner that judges with ``engine``.

        ``engine`` may be a ``VerdictEngine`` or a ``RuleEngine``; the runner
        only requires ``explain``, plus ``explain_for_tool`` when rule-aware
        judging is wanted. Returning a copy keeps the original runner usable.
        """
        clone = SafeRunner(engine=engine, bash=self._bash, timeout=self._timeout)
        return clone

    @property
    def engine(self):
        """The engine this runner judges with (read-only)."""
        return self._engine

    # -- public API ---------------------------------------------------

    def run_shell(
        self,
        command: str,
        cwd: str,
        intent_desc: str,
        expected_file: Optional[str] = None,
        expected_content: Optional[str] = None,
        witness_root: Optional[str] = None,
        timeout: Optional[float] = None,
        expected_files_modified: Optional[Sequence[str]] = None,
        repo_path: Optional[str] = None,
        allow_extra_changes: bool = False,
        reported_success: Optional[bool] = None,
        tool_name: Optional[str] = None,
        witness_scope: str = WITNESS_SCOPE_FULL,
    ) -> ExecutionResult:
        """Run ``command`` in ``cwd`` and judge the outcome.

        Three independent witnesses are available; supplying several makes
        them a conjunction, because evidence pointing in different directions
        is not a PASS.

        ``expected_file`` names the artefact that proves the intent landed.
        A relative path is resolved against ``witness_root``, which defaults
        to ``cwd`` for convenience. Pass ``witness_root`` explicitly whenever
        the intent lives somewhere the command does not control: that is the
        only way target drift is visible. ``expected_content`` is matched as a
        substring of the file's UTF-8 text.

        ``expected_files_modified`` names the paths the command was supposed
        to touch, relative to ``cwd``. The change set is read from git, not
        from the agent, and only *new* changes count: a baseline snapshot is
        taken before the command runs so pre-existing dirt is not mistaken for
        this command's effect. ``repo_path`` selects the repository and
        defaults to auto-discovery from ``cwd``; the git witness is the useful
        one when the file may have landed somewhere unexpected.

        By default the git change set must equal the expected set exactly, so
        an agent that edits the right file *and* something unrelated is judged
        as drift rather than success. Set ``allow_extra_changes=True`` to
        accept a superset instead.

        ``reported_success`` replaces the exit status as the source of the
        ``check`` observation. Use it when the claim reaching the agent came
        from a tool layer rather than from the command itself, because those
        are different observers: the tool layer sees the exit status and may
        misreport it, and the agent only ever sees the tool layer's answer.
        Judging the tool layer's claim against the command's own exit status
        would audit the wrong party, and would make a swallowed error
        invisible. When this is supplied, ``check_source`` records
        ``"protocol"`` so the audit trail shows where the claim came from.

        ``tool_name`` enables judgment-base rules. When the configured engine
        is rule-aware (it exposes ``explain_for_tool``), the observation set is
        handed over with ``tool_name`` so per-tool policy can tighten the
        lattice verdict. When it is not, this argument is ignored and the plain
        lattice decides -- so passing it can never loosen a verdict.

        ``witness_scope`` selects how much evidence to collect. ``"full"`` (the
        default) is the git change set plus a content read. ``"stat"`` is the
        innate tier: one ``os.stat`` per claimed path before the command and
        one after, so the effect is "existed and its mtime/size moved". It
        spawns no git process and reads no file. Two consequences are
        deliberate: ``expected_content`` is rejected (checking it would read
        the file) and ``unexpected_changes`` is always empty (nothing surveyed
        the tree, so claiming to know would be a fabrication).

        If ``"full"`` was requested but git cannot be read (not a repository,
        missing binary, or a timeout), the run **falls back to ``stat``** on
        exactly ``expected_files_modified`` / ``expected_file``. The command
        still runs. The trace records ``witness_scope="stat"``. This is not
        INVALID: a declared-file mtime/size change is a witness, just a
        weaker one than a change set.
        """
        if not isinstance(command, str) or not command.strip():
            raise ValueError("command must be a non-empty string")
        if not isinstance(cwd, str) or not cwd:
            raise ValueError("cwd must be a non-empty string")
        if witness_scope not in _SCOPES:
            raise ValueError(
                "witness_scope must be one of {}, got {!r}".format(
                    list(_SCOPES), witness_scope
                )
            )
        collected_scope = witness_scope
        stat_scope = collected_scope == WITNESS_SCOPE_STAT
        if expected_content is not None and expected_file is None:
            raise ValueError(
                "expected_content requires expected_file: content alone does "
                "not say which file to witness"
            )
        if stat_scope and expected_content is not None:
            # Silently dropping the content check would turn a caller's
            # assertion into a weaker one without saying so.
            raise ValueError(
                "expected_content cannot be checked with witness_scope='stat': "
                "the innate tier does not read the file; use witness_scope='full'"
            )
        if reported_success is not None and not isinstance(reported_success, bool):
            raise TypeError(
                "reported_success must be a bool or None, got {!r}".format(
                    type(reported_success).__name__
                )
            )

        expected_paths = self._normalise_expected(expected_files_modified)
        # Warn only. A missing parent is not a verdict: the command still
        # runs, and the post-effect witness still judges what actually landed.
        prechecks = self._missing_parent_prechecks(cwd, expected_paths)

        effective_timeout = self._timeout if timeout is None else float(timeout)
        if effective_timeout <= 0:
            raise ValueError("timeout must be positive")

        witness_root_abs = os.path.abspath(witness_root if witness_root else cwd)
        witness_path = None
        if expected_file is not None:
            witness_path = (
                expected_file
                if os.path.isabs(expected_file)
                else os.path.join(witness_root_abs, expected_file)
            )

        # The baseline must be captured before the command can touch anything.
        git_witness: Optional[GitWitness] = None
        baseline: Optional[Dict[str, str]] = None
        declared_paths = expected_paths
        if expected_paths is not None and not stat_scope:
            try:
                git_witness = GitWitness(
                    repo_path if repo_path else cwd, timeout=effective_timeout
                )
                # Map the caller's paths (relative to cwd) into repo-root space
                # before comparing them with what git reports. Skipping this
                # makes a correct edit inside a subdirectory look like drift.
                #
                # When cwd sits outside the repository -- the caller pointed
                # at one tree but ran the command somewhere else --
                # cwd-relative paths would be meaningless, so the repository
                # root becomes the base.
                repo_root = git_witness.repo_root
                cwd_abs = os.path.abspath(cwd)
                inside = cwd_abs == repo_root or cwd_abs.startswith(
                    repo_root + os.sep
                )
                expected_paths = tuple(
                    git_witness.resolve_expected(
                        expected_paths, cwd if inside else repo_root
                    )
                )
                baseline = git_witness.snapshot()
            except GitWitnessError as problem:
                # Not a repository, git missing, or a timeout (including a
                # tree too large to snapshot). Blocking the command or
                # answering INVALID would recreate the git wall: a declared
                # path can still be witnessed by mtime/size, and only those
                # paths are statted -- never a directory walk.
                _LOG.warning(
                    "git witness unavailable (%s); falling back to "
                    "declared-file mtime/size (witness_scope=stat)",
                    problem,
                )
                git_witness = None
                baseline = None
                expected_paths = declared_paths
                stat_scope = True
                collected_scope = WITNESS_SCOPE_STAT

        # Innate tier: capture the cheap baseline (mtime + size) before the
        # command runs, for exactly the paths the call claimed to touch.
        stat_targets: Tuple[str, ...] = ()
        stat_baseline: Optional[Dict[str, Optional[Tuple[int, int]]]] = None
        if stat_scope:
            stat_targets = self._stat_targets(witness_path, expected_paths, cwd)
            stat_baseline = self._stat_snapshot(stat_targets)

        exit_code, pipe_status, stdout, stderr, error = self._execute(
            command, cwd, effective_timeout
        )

        # The claim and the exit status are separate observations. When a tool
        # layer reported to the agent, that report is the claim under audit;
        # the exit status is only evidence about the command.
        if reported_success is None:
            check_observed = exit_code == 0
            check_source = "exit-status"
        else:
            check_observed = reported_success
            check_source = "protocol"

        # A witness read after a killed process describes an intermediate
        # world, so it is not evidence about the intent.
        timed_out = error is not None and "timed out" in error
        never_started = exit_code is None and not timed_out

        changed: Tuple[str, ...] = ()
        missing: Tuple[str, ...] = ()
        unexpected: Tuple[str, ...] = ()
        witness_mtime: Optional[float] = None
        # Set when a witness was requested but could not be read. It must end
        # the run as INVALID: the receipt may not claim "no effect" on behalf
        # of a witness that never got to look.
        observed_unknown = False

        if timed_out:
            effect_observed: Optional[bool] = None
        elif never_started:
            # Nothing executed, so this run cannot have changed anything.
            effect_observed = False
        elif stat_scope and stat_targets and stat_baseline is not None:
            # Innate tier. "It exists and its mtime or size moved" is the whole
            # claim; seeing that a correct edit *also* touched something else
            # is exactly what this tier cannot do, which is why overwriting a
            # file is declared high risk rather than left to it.
            modified, mtimes = self._stat_changes(stat_baseline)
            # Reported under the same names the caller used, so a trace reads
            # the same way whichever tier produced it.
            root = os.path.abspath(cwd)
            changed = tuple(self._observed_name(path, root) for path in modified)
            # "Missing" is the full tier's word for "named but not observed as
            # changed", and it means the same here: an untouched file and an
            # absent one both failed to show the claimed effect.
            unobserved = tuple(p for p in stat_baseline if p not in set(modified))
            missing = tuple(self._observed_name(path, root) for path in unobserved)
            effect_observed = not missing
            if witness_path is not None and witness_path in mtimes:
                witness_mtime = mtimes[witness_path] / 1e9
        elif witness_path is None and git_witness is None:
            # Nothing was named as evidence, so nothing can be observed.
            effect_observed = None
        else:
            effect_observed = True

            if witness_path is not None:
                landed = self._witness(witness_path, expected_content)
                if landed is None:
                    # The artefact exists but could not be read: that is an
                    # absence of evidence, not evidence of absence. Collapsing
                    # it to False would print "witness says no effect" in the
                    # receipt, which is a statement the witness never made.
                    observed_unknown = True
                elif not landed:
                    effect_observed = False

            if git_witness is not None and baseline is not None:
                assert expected_paths is not None
                try:
                    changed = tuple(git_witness.changed_since(baseline))
                except GitWitnessError as problem:
                    # An unreadable path in the change set is not a change.
                    _LOG.warning("git witness could not be completed: %s", problem)
                    observed_unknown = True
                    changed = ()
                wanted = tuple(expected_paths)
                # When a file witness is also in play, that artefact is part of
                # the intent by definition, so it is not "unexpected" drift.
                permitted = set(wanted)
                if witness_path is not None:
                    relative = self._repo_relative(witness_path, git_witness.repo_root)
                    if relative is not None:
                        permitted.add(relative)
                missing = tuple(p for p in wanted if p not in changed)
                unexpected = tuple(p for p in changed if p not in permitted)
                if missing:
                    effect_observed = False
                if unexpected and not allow_extra_changes:
                    effect_observed = False

        if observed_unknown:
            # An unreadable witness outranks anything else the block concluded:
            # whatever is in ``changed``/``missing`` was computed from a
            # partial read, so none of it is evidence.
            effect_observed = None

        # Map the three observations onto the engine's lattice.
        #
        # never_started -> intent None, so the engine reports NOT RUN. This is
        # deliberately not INVALID: INVALID means "the scenario ran but we have
        # no witness", whereas here nothing ran at all. effect=False is sound
        # rather than assumed -- nothing executed, so this run cannot have
        # produced the intended state. Rule 1 in the engine fires on a None
        # effect before it looks at intent, so passing None here would collapse
        # the distinction to INVALID.
        engine_intent: Optional[bool] = None if never_started else True

        # Which witness *types* were actually collected. A rule that demands a
        # witness type absent from this set is asking for evidence the run did
        # not produce, which the rule engine reports as INVALID rather than
        # letting the lattice's PASS stand.
        witnesses = set()
        if stat_scope:
            # "stat" is deliberately not reported as "file": the file's content
            # was never read, so claiming a file witness would satisfy a rule
            # that asked for evidence the innate tier did not collect.
            if stat_targets:
                witnesses.add("stat")
        else:
            if witness_path is not None:
                witnesses.add("file")
            if git_witness is not None:
                witnesses.add("git_diff")
        if check_source == "protocol":
            witnesses.add("agent_report")

        rule_aware = getattr(self._engine, "explain_for_tool", None)
        if tool_name is not None and callable(rule_aware):
            decision = rule_aware(
                tool_name,
                intent=engine_intent,
                effect=effect_observed,
                check=check_observed,
                witnesses=frozenset(witnesses),
            )
            verdict, reason = decision.verdict, decision.reason
            rule_id = decision.rule_id
            rules_matched = tuple(decision.matched_rule_ids)
            rules_violated = tuple(decision.violated_rule_ids)
        else:
            verdict, reason = self._engine.explain(
                intent=engine_intent,
                effect=effect_observed,
                check=check_observed,
            )
            rule_id = None
            rules_matched = ()
            rules_violated = ()

        if effect_observed is None and verdict is Verdict.INVALID:
            if observed_unknown:
                # Distinguish the two ways to have no witness. The receipt must
                # not tell the reader "you asked for nothing" when the truth is
                # "I was asked and could not look".
                reason = "{} (a witness was requested but could not be read; " \
                         "this is INVALID, not FAIL)".format(reason)
            else:
                reason = "{} (no independent witness requested)".format(reason)

        if verdict is Verdict.FAIL and (missing or unexpected):
            detail = []
            if missing:
                detail.append("expected but untouched: " + ", ".join(missing))
            if unexpected:
                detail.append("changed but unexpected: " + ", ".join(unexpected))
            reason = "{} ({})".format(reason, "; ".join(detail))

        # Say which tier produced the verdict. A PASS resting on an mtime is a
        # weaker claim than a PASS resting on a change set, and a trace that
        # hides the difference overstates every cheap green tick.
        if stat_scope and stat_targets:
            reason = "{} [innate tier: existence and mtime only, no git change set]".format(
                reason
            )

        # Record the tool layer's own contradiction: it told the agent the call
        # succeeded while the command it wrapped exited non-zero.
        if (
            check_source == "protocol"
            and exit_code is not None
            and check_observed
            and exit_code != 0
        ):
            reason = "{} [tool layer reported success, underlying command exited {}]".format(
                reason, exit_code
            )

        return ExecutionResult(
            intent=intent_desc,
            effect_observed=effect_observed,
            check_observed=check_observed,
            verdict=verdict,
            command=command,
            cwd=os.path.abspath(cwd),
            exit_code=exit_code,
            pipe_status=pipe_status,
            witness_path=witness_path,
            reason=reason,
            stdout=stdout,
            stderr=stderr,
            error=error,
            check_source=check_source,
            git_repo=git_witness.repo_root if git_witness is not None else None,
            changed_files=changed,
            missing_expected=missing,
            unexpected_changes=unexpected,
            rule_id=rule_id,
            rules_matched=rules_matched,
            rules_violated=rules_violated,
            witness_scope=collected_scope,
            witness_mtime=witness_mtime,
            prechecks=prechecks,
        )

    def raw_exit_status(
        self,
        command: str,
        cwd: Optional[str] = None,
        pipefail: bool = True,
        timeout: Optional[float] = None,
    ) -> int:
        """Return the exit status of ``command``, optionally pipeline-blind.

        Kept separate from ``run_shell`` because it is a diagnostic: it runs
        the command again (side effects included) and is meant for explaining
        *why* a status was captured, not for producing a verdict.
        """
        argv = [self._bash]
        if pipefail:
            argv += ["-o", "pipefail"]
        argv += ["-c", command]

        completed = subprocess.run(
            argv,
            cwd=os.path.abspath(cwd) if cwd else None,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            errors="replace",
            timeout=self._timeout if timeout is None else float(timeout),
        )
        return completed.returncode

    # -- internals ----------------------------------------------------

    @staticmethod
    def _missing_parent_prechecks(
        cwd: str, expected_paths: Optional[Tuple[str, ...]]
    ) -> Tuple[ParentPrecheck, ...]:
        """``exists``/isdir of each declared path's dirname, before execute."""
        if not expected_paths:
            return ()
        stamp = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
        base = os.path.abspath(cwd)
        found: List[ParentPrecheck] = []
        for path in expected_paths:
            absolute = (
                path if os.path.isabs(path) else os.path.abspath(os.path.join(base, path))
            )
            parent = os.path.dirname(absolute)
            if not parent:
                parent = base
            if os.path.isdir(parent):
                continue
            relative = os.path.relpath(parent, base)
            missing_dir = (
                parent
                if relative.startswith(os.pardir + os.sep) or relative == os.pardir
                else relative
            )
            found.append(
                ParentPrecheck(
                    path=path,
                    missing_dir=missing_dir.replace("\\", "/"),
                    timestamp=stamp,
                )
            )
        return tuple(found)

    @staticmethod
    def _normalise_expected(
        expected: Optional[Sequence[str]],
    ) -> Optional[Tuple[str, ...]]:
        """Validate the expected change set without touching the filesystem."""
        if expected is None:
            return None
        if isinstance(expected, (str, bytes)):
            raise TypeError(
                "expected_files_modified must be a sequence of paths, not a "
                "single string; wrap it in a list"
            )
        try:
            values = tuple(expected)
        except TypeError:
            raise TypeError(
                "expected_files_modified must be a sequence of paths"
            ) from None
        if not values:
            raise ValueError(
                "expected_files_modified is empty: use expected_file for "
                "artefact witnesses, or omit the argument entirely"
            )
        for entry in values:
            if not isinstance(entry, str) or not entry.strip():
                raise ValueError("expected paths must be non-empty strings")
        return values

    @staticmethod
    def _repo_relative(path: str, repo_root: str) -> Optional[str]:
        relative = os.path.relpath(os.path.abspath(path), repo_root)
        if relative == os.pardir or relative.startswith(os.pardir + os.sep):
            return None
        return relative.replace(os.sep, "/")

    @classmethod
    def _observed_name(cls, path: str, root: str) -> str:
        """Name a witnessed path relative to ``root``, falling back to absolute.

        Used so the innate tier's path reporting matches the full tier's: a
        trace should not need to know which tier produced it in order to read
        which files are named.
        """
        relative = cls._repo_relative(path, root)
        return path if relative is None else relative

    def _execute(
        self, command: str, cwd: str, timeout: float
    ) -> Tuple[Optional[int], Tuple[int, ...], str, str, Optional[str]]:
        """Run the command; return (exit_code, pipestatus, out, err, error)."""
        cwd_abs = os.path.abspath(cwd)

        with tempfile.TemporaryDirectory(prefix="harness-run-") as scratch:
            status_file = os.path.join(scratch, "pipestatus.txt")
            wrapper = os.path.join(scratch, "run.sh")
            body = _WRAPPER_TEMPLATE.format(
                command=command if command.endswith("\n") else command + "\n",
                status_file=shlex.quote(status_file),
            )
            with open(wrapper, "w", encoding="utf-8") as handle:
                handle.write(body)
            os.chmod(wrapper, 0o700)

            try:
                completed = subprocess.run(
                    [self._bash, wrapper],
                    cwd=cwd_abs,
                    stdin=subprocess.DEVNULL,
                    capture_output=True,
                    text=True,
                    errors="replace",
                    timeout=timeout,
                )
            except subprocess.TimeoutExpired as expired:
                return (
                    None,
                    (),
                    _as_text(expired.stdout),
                    _as_text(expired.stderr),
                    "command timed out after {:.1f}s".format(timeout),
                )
            except OSError as problem:
                return (
                    None,
                    (),
                    "",
                    "",
                    "command could not be executed: {}".format(problem),
                )

            pipe_status = self._read_pipe_status(status_file)
            # A top-level ``exit`` in the command terminates the wrapper
            # before the status file is written, so the array is missing even
            # though the process status is still the command's own.
            if not pipe_status and completed.returncode is not None:
                pipe_status = (completed.returncode,)
            return (
                completed.returncode,
                pipe_status,
                completed.stdout,
                completed.stderr,
                None,
            )

    @staticmethod
    def _read_pipe_status(status_file: str) -> Tuple[int, ...]:
        """Parse the PIPESTATUS line written by the wrapper."""
        try:
            text = _read_text(status_file).strip()
        except OSError:
            return ()
        if not text:
            return ()
        try:
            return tuple(int(part) for part in text.split())
        except ValueError:
            _LOG.debug("unparsable pipestatus: %r", text)
            return ()

    @staticmethod
    def _stat_targets(
        witness_path: Optional[str],
        expected_paths: Optional[Tuple[str, ...]],
        cwd: str,
    ) -> Tuple[str, ...]:
        """The absolute paths the innate tier will watch, without duplicates.

        ``expected_paths`` here are still cwd-relative: with no git process
        there is no repository root to resolve them against, and pretending
        otherwise would make the same call mean two different things depending
        on the tier that judged it.
        """
        targets: List[str] = []
        if witness_path is not None:
            targets.append(witness_path)
        if expected_paths is not None:
            base = os.path.abspath(cwd)
            for path in expected_paths:
                absolute = path if os.path.isabs(path) else os.path.join(base, path)
                if absolute not in targets:
                    targets.append(absolute)
        return tuple(targets)

    @staticmethod
    def _stat_snapshot(paths: Sequence[str]) -> Dict[str, Optional[Tuple[int, int]]]:
        """``(mtime_ns, size)`` per path, or ``None`` where it does not exist.

        Size rides along because a filesystem with coarse timestamps can hide a
        same-second rewrite of different length; it cannot hide a same-second
        rewrite of identical length, which is the residual blind spot of this
        tier and the reason the overwrite path is declared high risk.
        """
        snapshot: Dict[str, Optional[Tuple[int, int]]] = {}
        for path in paths:
            snapshot[path] = SafeRunner._stat_one(path)
        return snapshot

    @staticmethod
    def _stat_one(path: str) -> Optional[Tuple[int, int]]:
        try:
            info = os.stat(path)
        except OSError:
            return None
        return (info.st_mtime_ns, info.st_size)

    @classmethod
    def _stat_changes(
        cls, baseline: Dict[str, Optional[Tuple[int, int]]]
    ) -> Tuple[Tuple[str, ...], Dict[str, int]]:
        """Compare the baseline with the world as it is now.

        Returns (modified, mtimes). "Modified" includes a path that did not
        exist before and does now: creating the file is the effect.
        """
        modified: List[str] = []
        mtimes: Dict[str, int] = {}
        for path, before in baseline.items():
            after = cls._stat_one(path)
            if after is None:
                continue
            mtimes[path] = after[0]
            if before is None or after != before:
                modified.append(path)
        return tuple(modified), mtimes

    @staticmethod
    def _witness(path: str, expected_content: Optional[str]) -> Optional[bool]:
        """Read the witnessed artefact. Returns whether the intent landed.

        ``None`` means "the artefact is there but could not be read", which is
        an absence of evidence and must not be reported as a failed intent.
        """
        if not os.path.exists(path):
            return False
        if os.path.isdir(path):
            # A directory where a file was expected is not the intent.
            return False
        try:
            content = _read_text(path)
        except OSError as problem:
            _LOG.warning("witness %s could not be read: %s", path, problem)
            return None
        if expected_content is None:
            return True
        return expected_content in content


def _as_text(payload: object) -> str:
    if payload is None:
        return ""
    if isinstance(payload, bytes):
        return payload.decode("utf-8", errors="replace")
    return str(payload)
